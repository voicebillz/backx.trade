#!/usr/bin/env python3
"""Copies the compiled init code of the contracts the admin portal can deploy into server/src/artifacts.json.
Run after every contract change:  forge build && python3 script/export-artifacts.py
The portal deploys with CREATE2 (deterministic deployer), so the address follows from this exact init code."""
import json, hashlib, os, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["BackxReserveVault", "BackxReserveSecurityFund", "BackxHedgeManager", "BackxShortManager", "BackxMarketFactory", "BackxTreasury", "ERC1967Proxy"]
out = {}
for n in NAMES:
    j = json.load(open(os.path.join(ROOT, "out", f"{n}.sol", f"{n}.json")))
    init = j["bytecode"]["object"]
    runtime = j["deployedBytecode"]["object"]
    out[n] = {"initcode": init, "runtimeSize": (len(runtime) - 2) // 2}
src = subprocess.run(["git", "log", "-1", "--format=%h", "--", "src"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
out["_meta"] = {"sourceCommit": src, "solc": "0.8.24", "note": "generated by contracts/script/export-artifacts.py"}
dst = os.path.join(ROOT, "..", "server", "src", "artifacts.json")
json.dump(out, open(dst, "w"), separators=(",", ":"))
print("wrote", os.path.normpath(dst), {k: v["runtimeSize"] for k, v in out.items() if k != "_meta"})
